  assert.equal(await page.evaluate(()=>LIFT.S.goals.lifts),2);
  await page.click('[data-length="30"]');
  const quick=await page.evaluate(()=>LIFT.S.days.map(day=>WorkoutPlan.preview(day,LIFT.S.plan.length,LIFT.S.settings)));
  quick.forEach((day,index)=>{
   const lateral=two[index].exercises.find((exercise,i)=>i>=3&&/lateral raise/i.test(exercise.name));
   assert.ok(lateral,'source A/B includes a lateral raise after the core movements');
   assert.deepEqual(day.exercises.map(e=>e.id),[...two[index].exercises.slice(0,3).map(e=>e.id),lateral.id],'Quick keeps the first three movements plus lateral raise');
   assert.equal(day.exercises.reduce((n,e)=>n+e.sets,0),10,'Quick has ten working sets');
  });
  assert.deepEqual(await page.evaluate(()=>LIFT.S.days),two,'Quick does not mutate the saved full profile');
  await page.click('[data-length="full"]');
  assert.deepEqual(await page.evaluate(()=>LIFT.S.days.map(day=>WorkoutPlan.preview(day,LIFT.S.plan.length,LIFT.S.settings).exercises.reduce((n,e)=>n+e.sets,0))),[14,14]);
