  assert.equal(swaps.requiredBecameOptional,false,'optional library candidate does not make a required slot optional');
  assert.equal(swaps.optionalStayedOptional,true,'required library candidate does not make an optional slot required');
  assert.equal(swaps.unchanged,true,'constructing swap replacements does not alter the active workout');
