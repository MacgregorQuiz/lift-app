  assert.equal(await page.evaluate(()=>LIFT.S.sessions.at(-1).optional),true,'history retains the optional marker');
  assert.equal(await page.evaluate(()=>LIFT.nextDay().id),core[1].id,'recording optional C does not interrupt A/B rotation');
  assert.equal(await page.evaluate(()=>weekCount(weekStart())),1,'A plus optional C remains one of two core lifts');
  await page.click('nav [data-v="home"]');await page.click('#start');
  assert.equal(await page.evaluate(()=>LIFT.S.active.dayId),core[1].id,'B follows manual optional C');
  const active=await page.evaluate(()=>JSON.parse(JSON.stringify(LIFT.S.active)));
  const logged=await page.evaluate(()=>JSON.parse(JSON.stringify(LIFT.S.sessions)));
