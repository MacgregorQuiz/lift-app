  assert.equal(await page.evaluate(()=>LIFT.S.plan.tpl),process.env.FIELD_GUIDE_DEFAULT||'field4','home action uses the selected field-guide default');
  assert.equal(await page.evaluate(()=>LIFT.S.plan.length),'full','first selection preserves the complete profile');
