  assert.equal(await page.evaluate(()=>weekCount(weekStart())),1,'A counts as one core lift');
  await page.click('nav [data-v="home"]');
  const optionalButton=page.locator(`.alt[data-id="${optional[0].id}"]`);
  assert.match(await optionalButton.innerText(),/optional/i);await optionalButton.click();
  assert.equal(await page.evaluate(()=>LIFT.S.active.optional),true,'optional status travels into the session');
  assert.match(await page.locator('.optional-session').innerText(),/optional/i,'active session carries an optional badge');
  const swaps=await page.evaluate(()=>{
   const workout=LIFT.S.active,required=workout.entries.find(entry=>!entry.optionalAccessory),optional=workout.entries.find(entry=>entry.optionalAccessory);
   const library=exAll(),optionalCandidate=library.find(entry=>entry.optionalAccessory),requiredCandidate=library.find(entry=>!entry.optionalAccessory);
   if(!required||!optional||!optionalCandidate||!requiredCandidate)return{fixtures:false};
   const before=JSON.stringify(workout);
   const requiredReplacement=mkEntry(optionalCandidate,workout,required),optionalReplacement=mkEntry(requiredCandidate,workout,optional);
   return{fixtures:true,requiredBecameOptional:requiredReplacement.optionalAccessory===true,optionalStayedOptional:optionalReplacement.optionalAccessory===true,unchanged:JSON.stringify(workout)===before};
  });
